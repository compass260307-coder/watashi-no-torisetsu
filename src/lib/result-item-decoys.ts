function decoy(
  headings: readonly string[],
  items: readonly { lead: string; body: string }[],
): ResultItem[] {
  const zipped = zipResultItems(headings, items);
  if (!zipped) throw new Error("result-item-decoys: 見出しと見本の数が合っていない");
  return zipped;
}

