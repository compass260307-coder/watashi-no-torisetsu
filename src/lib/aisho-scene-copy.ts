type Tri = "both" | "one" | "none";
type Bi = "match" | "diff";

function tri(a: boolean, b: boolean): Tri {
  const c = (a ? 1 : 0) + (b ? 1 : 0);
  return c === 2 ? "both" : c === 1 ? "one" : "none";
}
function bi(a: boolean, b: boolean): Bi {
  return a === b ? "match" : "diff";
}

