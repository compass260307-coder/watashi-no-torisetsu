export function buildMoshimoScenes(
  scores: Partial<Record<BigFiveDimension, number>>,
  unlocked: boolean,
  locale: ResultLocale = "ja",
): MoshimoScene[] {
  const hl = (d: BigFiveDimension): "H" | "L" =>
    (typeof scores[d] === "number" ? (scores[d] as number) : 5) >= 5
      ? "H"
      : "L";
  return SCENES.map((scene, index) => {
    const koCopy = locale === "ko" ? KO_SCENE_COPY[index] : undefined;
    const gatedAndLocked = scene.gated && !unlocked;
    return {
      title: koCopy?.title ?? scene.title,
      chipLabel:
        koCopy?.short ??
        scene.short ??
        (koCopy
          ? koCopy.title.replace(/(일 때의|때의|밤의) 나$/, "")
          : scene.title.replace(/(で)?のあなた$/, "")),
      color: scene.color,
      body: gatedAndLocked
        ? ""
        : koCopy
          ? `${koCopy.main[hl(scene.main.dim)]} ${koCopy.spice[hl(scene.spice.dim)]}`
          : `${scene.main.prose[hl(scene.main.dim)]}${scene.spice.prose[hl(scene.spice.dim)]}`,
      locked: gatedAndLocked,
    };
  });
}
