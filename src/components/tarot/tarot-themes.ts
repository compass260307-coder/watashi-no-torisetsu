export type TarotRoomLocale = "ja" | "ko";

/** テーマ表示用の文言 (ja / ko)。 */
export function tarotThemes(locale: TarotRoomLocale) {
  return locale === "ko" ? KO_TAROT_THEMES : TAROT_THEMES;
}

/** 大アルカナのカード名 (ja / ko)。 */
export function arcanaName(locale: TarotRoomLocale, index: number): string {
  return (locale === "ko" ? KO_ARCANA : ARCANA)[index][0];
}
